// GtgEndpointsCard — Google tag gateway status for a client, the gateway paths
// Atlas knows about, and the operator's add / remove / "Verify now" controls
// (docs/prd/google-tag-gateway.md §6, §9). No uplift figures: Atlas states what it
// observed and verified, nothing Google markets.

import { useCallback, useEffect, useState } from 'react';
import { Loader2 } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { gtgApi, type GtgEndpoint, type GtgOverview, type GtgVerifyResult } from '@/lib/api/gtgApi';
import { GTG_STATUS_LABELS, GTG_STATUS_SUBTEXT, gtgTone, type GtgTone } from '@/lib/gtgStatus';

interface GtgEndpointsCardProps {
  orgId: string;
  clientId: string;
}

const TONE_STYLE: Record<GtgTone, string> = {
  good: 'bg-severity-success-bg text-severity-success',
  warning: 'bg-severity-warning-bg text-severity-warning',
  critical: 'bg-severity-critical-bg text-severity-critical',
  neutral: 'bg-console-chip text-console-fg-muted',
};

const SOURCE_LABEL: Record<GtgEndpoint['source'], string> = {
  detected: 'Detected on the site',
  operator_declared: 'Added by you',
  atlas_generated: 'Generated by Atlas',
};

const VERDICT_TEXT: Record<GtgVerifyResult['results'][number]['verdict'], string> = {
  ok: 'Healthy, location headers arriving',
  no_geo: 'Routes, but location headers are missing',
  broken: 'Failed its health check',
  inconclusive: 'Could not be checked right now',
};

function Chip({ children, className }: { children: React.ReactNode; className: string }) {
  return <span className={`inline-flex w-fit items-center rounded-full px-2 py-0.5 text-[10px] font-medium ${className}`}>{children}</span>;
}

function endpointState(e: GtgEndpoint): { label: string; className: string } {
  if (e.is_verified && e.geo_verified) return { label: 'Verified', className: TONE_STYLE.good };
  if (e.is_verified) return { label: 'Routes, no location headers', className: TONE_STYLE.warning };
  return { label: 'Not verified', className: TONE_STYLE.neutral };
}

const inputClass = 'mt-1 block w-full rounded border border-console-border bg-console-bg px-2 py-1 font-mono text-sm';

export function GtgEndpointsCard({ orgId, clientId }: GtgEndpointsCardProps) {
  const [overview, setOverview] = useState<GtgOverview | null>(null);
  const [verify, setVerify] = useState<GtgVerifyResult | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState<'add' | 'verify' | string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const [hostname, setHostname] = useState('');
  const [path, setPath] = useState('');
  const [tagId, setTagId] = useState('');

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      setOverview(await gtgApi.getOverview(orgId, clientId));
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Failed to load gateway status');
    } finally {
      setLoading(false);
    }
  }, [orgId, clientId]);

  useEffect(() => { load(); }, [load]);

  async function add(e: React.FormEvent) {
    e.preventDefault();
    setBusy('add');
    setError(null);
    try {
      await gtgApi.addEndpoint(orgId, clientId, { hostname, reserved_path: path, tag_or_container: tagId });
      setHostname(''); setPath(''); setTagId('');
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to save the path');
    } finally {
      setBusy(null);
    }
  }

  async function remove(id: string) {
    setBusy(id);
    setError(null);
    try {
      await gtgApi.removeEndpoint(orgId, clientId, id);
      setVerify(null);
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to remove the path');
    } finally {
      setBusy(null);
    }
  }

  async function runVerify() {
    setBusy('verify');
    setError(null);
    try {
      setVerify(await gtgApi.verify(orgId, clientId));
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Verification failed');
    } finally {
      setBusy(null);
    }
  }

  return (
    <div className="space-y-4">
      <Card className="border-console-border bg-console-surface">
        <CardHeader className="pb-3">
          <CardTitle className="font-heading text-base text-console-fg">Google tag gateway</CardTitle>
          <p className="text-sm text-console-fg-muted">
            Serves Google tags from a reserved path on this client&apos;s own domain. Atlas checks the paths listed here, using
            Google&apos;s own health checks, and never probes a path that has not been registered or detected on the site.
          </p>
        </CardHeader>
        <CardContent className="space-y-4">
          {loading ? (
            <div className="flex items-center gap-2 text-sm text-console-fg-muted">
              <Loader2 className="h-4 w-4 animate-spin" /> Loading gateway status…
            </div>
          ) : overview ? (
            <>
              <div className="space-y-1">
                <Chip className={`${TONE_STYLE[gtgTone(overview.status)]} !text-xs`}>{GTG_STATUS_LABELS[overview.status]}</Chip>
                <p className="text-sm text-console-fg-muted">{GTG_STATUS_SUBTEXT[overview.status]}</p>
              </div>

              {overview.endpoints.length === 0 ? (
                <p className="text-sm text-console-fg-muted">
                  No gateway path registered. If this client runs one, add it below. Atlas also registers one automatically when a scan finds a
                  Google tag loading through a reserved path.
                </p>
              ) : (
                <ul className="space-y-2">
                  {overview.endpoints.map((ep) => {
                    const state = endpointState(ep);
                    return (
                      <li key={ep.id} className="rounded border border-console-border p-3">
                        <div className="flex flex-wrap items-center justify-between gap-2">
                          <p className="font-mono text-sm text-console-fg">{ep.hostname}{ep.reserved_path}</p>
                          <div className="flex items-center gap-2">
                            <Chip className={state.className}>{state.label}</Chip>
                            <Button size="sm" variant="ghost" disabled={busy !== null} onClick={() => remove(ep.id)} aria-label={`Remove ${ep.reserved_path}`}>
                              {busy === ep.id ? 'Removing…' : 'Remove'}
                            </Button>
                          </div>
                        </div>
                        <p className="mt-1 text-xs text-console-fg-subtle">
                          <span className="font-mono">{ep.tag_or_container}</span> · {SOURCE_LABEL[ep.source]}
                          {ep.verified_at ? ` · last verified ${new Date(ep.verified_at).toLocaleString()}` : ''}
                        </p>
                      </li>
                    );
                  })}
                </ul>
              )}

              <div className="flex flex-wrap items-center gap-3">
                <Button size="sm" onClick={runVerify} disabled={busy !== null || overview.endpoints.length === 0}>
                  {busy === 'verify' ? 'Verifying…' : 'Verify now'}
                </Button>
                {overview.probe_checked_at && (
                  <span className="text-xs text-console-fg-subtle">Last checked {new Date(overview.probe_checked_at).toLocaleString()}</span>
                )}
              </div>

              {verify && (
                <ul className="space-y-1 text-sm" aria-label="Verification results">
                  {verify.results.map((r) => {
                    const ep = overview.endpoints.find((e) => e.id === r.endpoint_id);
                    return (
                      <li key={r.endpoint_id} className="text-console-fg-muted">
                        <span className="font-mono text-console-fg">{ep ? `${ep.hostname}${ep.reserved_path}` : r.endpoint_id}</span>: {VERDICT_TEXT[r.verdict]}
                        {r.message ? ` (${r.message})` : ''}
                      </li>
                    );
                  })}
                </ul>
              )}
            </>
          ) : null}

          {error && <p className="text-sm text-severity-critical">{error}</p>}
        </CardContent>
      </Card>

      <Card className="border-console-border bg-console-surface">
        <CardHeader className="pb-3">
          <CardTitle className="font-heading text-sm text-console-fg">Register a gateway path</CardTitle>
        </CardHeader>
        <CardContent>
          <form onSubmit={add} className="grid gap-3 sm:grid-cols-3">
            <label className="text-sm text-console-fg">
              Hostname
              <input className={inputClass} value={hostname} onChange={(e) => setHostname(e.target.value)} placeholder="www.example.com" required />
            </label>
            <label className="text-sm text-console-fg">
              Reserved path
              <input className={inputClass} value={path} onChange={(e) => setPath(e.target.value)} placeholder="/metrics" required />
            </label>
            <label className="text-sm text-console-fg">
              GTM container or tag ID
              <input className={inputClass} value={tagId} onChange={(e) => setTagId(e.target.value)} placeholder="GTM-XXXXXXX" required />
            </label>
            <div className="sm:col-span-3">
              <Button type="submit" size="sm" variant="outline" disabled={busy !== null}>
                {busy === 'add' ? 'Saving…' : 'Save path'}
              </Button>
            </div>
          </form>
        </CardContent>
      </Card>
    </div>
  );
}
